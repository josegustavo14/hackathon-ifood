from typing import Any, Protocol

from app.models.nutrition import NutritionFacts
from app.models.cart import CartProposal
from app.models.nutrition import NutritionCalculation
from app.models.product import ProductCandidate
from app.models.recipe import Recipe
from app.models.shopping import ShoppingList
from app.shopping.models import ShoppingPlan, ShoppingPlanRequest


class RecipeProvider(Protocol):
    async def search(self, query: str) -> list[Recipe]: ...
    async def get_by_id(self, recipe_id: str) -> Recipe | None: ...


class IFoodGateway(Protocol):
    async def list_tools(self) -> list[dict[str, Any]]: ...
    async def list_addresses(self): ...
    async def search_offers(self, query: str, **kwargs): ...
    async def browse_offers(self, **kwargs): ...
    async def search_products(self, query: str, merchant_id: str | None = None, **kwargs) -> list[ProductCandidate]: ...
    async def get_item(self, item_id: str, merchant_id: str, **kwargs): ...
    async def get_merchant(self, merchant_id: str, **kwargs): ...


class NutritionProvider(Protocol):
    async def calculate(self, recipe: Recipe, servings: int, include_optional: bool = False) -> NutritionCalculation: ...


class ShoppingEngine(Protocol):
    def plan(self, request: ShoppingPlanRequest) -> ShoppingPlan: ...
    def calculate(self, recipe: Recipe, servings: int) -> ShoppingList: ...
    def match_products(self, shopping_list: ShoppingList, products: list[ProductCandidate]) -> ShoppingList: ...
